-- Schema immediately before the PricingAccount migration.
-- Existing installations baseline at this version; empty databases execute it.
CREATE TABLE client (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255),
    name VARCHAR(50) NOT NULL,
    company VARCHAR(100),
    phone VARCHAR(20),
    provider_id VARCHAR(255),
    provider VARCHAR(255),
    status VARCHAR(20) NOT NULL,
    plan VARCHAR(20),
    free_promotion_page_count INTEGER
);

CREATE TABLE client_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    client_id BIGINT NOT NULL REFERENCES client(id),
    target_url VARCHAR(2048) NOT NULL,
    site_name VARCHAR(255) NOT NULL,
    service_type VARCHAR(100) NOT NULL,
    target_engine VARCHAR(100),
    analysis_items TEXT,
    contact_name VARCHAR(100),
    contact_phone VARCHAR(50),
    contact_email VARCHAR(255),
    contact_org VARCHAR(255),
    memo TEXT,
    domain_status VARCHAR(255) NOT NULL,
    resource_key VARCHAR(36) NOT NULL UNIQUE
);

CREATE TABLE analysis_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    order_id BIGINT NOT NULL UNIQUE REFERENCES client_order(id),
    status VARCHAR(30) NOT NULL,
    attempts INTEGER NOT NULL,
    max_attempts INTEGER NOT NULL,
    last_failure_stage TEXT,
    error_message TEXT,
    next_run_at TIMESTAMP(6) NOT NULL,
    locked_at TIMESTAMP(6)
);

CREATE TABLE analysis_report (
    order_id BIGINT PRIMARY KEY REFERENCES client_order(id),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    raw_scraped_data JSONB,
    raw_ai_log JSONB,
    processed_result JSONB,
    report_status VARCHAR(20) NOT NULL,
    deleted_at TIMESTAMP(6)
);

CREATE TABLE pack_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES client(id),
    purchased_at TIMESTAMP(6) NOT NULL,
    expired_at TIMESTAMP(6) NOT NULL,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_pages INTEGER NOT NULL,
    remaining_pages INTEGER NOT NULL,
    price_paid NUMERIC(10,2) NOT NULL
);

CREATE TABLE partner_subscription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES client(id),
    purchased_at TIMESTAMP(6) NOT NULL,
    expired_at TIMESTAMP(6) NOT NULL,
    tier VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    monthly_price NUMERIC(10,2) NOT NULL,
    price_lock_until TIMESTAMP(6),
    CONSTRAINT partner_subscription_status_check
        CHECK (status IN ('PENDING_PAYMENT', 'ACTIVE', 'CANCELLED'))
);

CREATE TABLE academy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    partner_subscription_id BIGINT NOT NULL REFERENCES partner_subscription(id),
    name VARCHAR(100) NOT NULL,
    domain VARCHAR(255) NOT NULL,
    size_type VARCHAR(20) NOT NULL,
    noise_filter_enabled BOOLEAN NOT NULL,
    monthly_pages_used INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE partner_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    order_id BIGINT NOT NULL UNIQUE REFERENCES client_order(id),
    academy_id BIGINT NOT NULL REFERENCES academy(id)
);
