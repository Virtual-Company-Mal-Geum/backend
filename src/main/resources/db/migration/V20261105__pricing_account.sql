-- Flyway가 애플리케이션 시작 시 적용한다. 과거 무료 사용량은 추정하지 않는다.

CREATE TABLE IF NOT EXISTS pricing_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL UNIQUE REFERENCES client(id),
    scan_usage_month DATE NOT NULL,
    free_scan_used_count INTEGER NOT NULL DEFAULT 0 CHECK (free_scan_used_count BETWEEN 0 AND 5)
);

INSERT INTO pricing_account (client_id, scan_usage_month, free_scan_used_count)
SELECT id, date_trunc('month', CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date, 0
FROM client
ON CONFLICT (client_id) DO NOTHING;

ALTER TABLE pack_order ADD COLUMN IF NOT EXISTS pricing_account_id BIGINT;
ALTER TABLE partner_subscription ADD COLUMN IF NOT EXISTS pricing_account_id BIGINT;

DO $$
DECLARE
    product_table TEXT;
    has_legacy_owner BOOLEAN;
    invalid_count BIGINT;
BEGIN
    FOREACH product_table IN ARRAY ARRAY['pack_order', 'partner_subscription'] LOOP
        SELECT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = current_schema() AND table_name = product_table AND column_name = 'client_id'
        ) INTO has_legacy_owner;

        IF has_legacy_owner THEN
            EXECUTE format('UPDATE %I p SET pricing_account_id = a.id FROM pricing_account a
                            WHERE p.client_id = a.client_id AND p.pricing_account_id IS NULL', product_table);
            EXECUTE format('SELECT count(*) FROM %I p JOIN pricing_account a ON a.id = p.pricing_account_id
                            WHERE p.client_id IS DISTINCT FROM a.client_id', product_table) INTO invalid_count;
            IF invalid_count > 0 THEN
                RAISE EXCEPTION '% 소유 회원 불일치: %행', product_table, invalid_count;
            END IF;
        END IF;

        EXECUTE format('SELECT count(*) FROM %I p LEFT JOIN pricing_account a ON a.id = p.pricing_account_id
                        WHERE a.id IS NULL', product_table) INTO invalid_count;
        IF invalid_count > 0 THEN
            RAISE EXCEPTION '% 중앙 계정 이전 누락: %행', product_table, invalid_count;
        END IF;

        EXECUTE format('ALTER TABLE %I ALTER COLUMN pricing_account_id SET NOT NULL', product_table);
        IF NOT EXISTS (SELECT 1 FROM pg_constraint
                       WHERE conrelid = to_regclass(product_table)
                         AND conname = product_table || '_pricing_account_fk') THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (pricing_account_id) REFERENCES pricing_account(id)',
                           product_table, product_table || '_pricing_account_fk');
        END IF;
        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (pricing_account_id)',
                       product_table || '_pricing_account_idx', product_table);
        EXECUTE format('ALTER TABLE %I DROP COLUMN IF EXISTS client_id', product_table);
    END LOOP;
END $$;

ALTER TABLE client_order ADD COLUMN IF NOT EXISTS pricing_mode_at_acceptance VARCHAR(20);
ALTER TABLE client_order ADD COLUMN IF NOT EXISTS free_scan_usage_month DATE;

