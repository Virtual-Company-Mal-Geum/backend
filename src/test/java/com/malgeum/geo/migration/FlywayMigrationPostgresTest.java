package com.malgeum.geo.migration;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.sql.Connection;
import java.sql.Statement;
import java.util.Map;
import java.util.UUID;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.FlywayException;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.orm.jpa.LocalContainerEntityManagerFactoryBean;
import org.springframework.orm.jpa.vendor.HibernateJpaVendorAdapter;

@EnabledIfEnvironmentVariable(named = "MIGRATION_TEST_DB_URL", matches = "jdbc:postgresql:.*")
class FlywayMigrationPostgresTest {
    private final String schema = "flyway_test_" + UUID.randomUUID().toString().replace("-", "");
    private final DriverManagerDataSource dataSource = new DriverManagerDataSource(
            System.getenv("MIGRATION_TEST_DB_URL"),
            System.getenv().getOrDefault("MIGRATION_TEST_DB_USER", "postgres"),
            System.getenv().getOrDefault("MIGRATION_TEST_DB_PASSWORD", ""));

    @AfterEach
    void removeTestSchema() throws Exception {
        execute("DROP SCHEMA IF EXISTS " + schema + " CASCADE");
    }

    @Test
    void emptyDatabaseMigratesAndMatchesAllJpaEntities() {
        Flyway flyway = flyway(false);
        assertThat(flyway.migrate().migrationsExecuted).isEqualTo(4);
        validateJpaMappings();
        assertThat(flyway.migrate().migrationsExecuted).isZero();
        assertThat(flyway.info().applied()).hasSize(4);
    }

    @Test
    void existingDatabaseIsBaselinedAndMigratedWithoutLosingPurchases() throws Exception {
        createLegacyDatabase();
        Flyway flyway = flyway(true);
        assertThat(flyway.migrate().migrationsExecuted).isEqualTo(3);
        validateJpaMappings();
        assertThat(query("SELECT remaining_pages FROM pack_order WHERE id=33")).isEqualTo("4");
        assertThat(query("SELECT price_paid FROM pack_order WHERE id=33")).isEqualTo("49000.00");
        assertThat(query("SELECT a.client_id FROM pricing_account a JOIN pack_order p ON p.pricing_account_id=a.id WHERE p.id=33"))
                .isEqualTo("11");
        assertThat(query("SELECT status FROM partner_subscription WHERE id=44")).isEqualTo("ACTIVE");
        assertThat(query("SELECT status FROM partner_subscription WHERE id=45")).isEqualTo("INACTIVE");
        assertThat(query("SELECT tier FROM partner_subscription WHERE id=44")).isEqualTo("PARTNER");
        assertThat(query("SELECT count(*) FROM pricing_account")).isEqualTo("2");
        assertThat(flyway.migrate().migrationsExecuted).isZero();
    }

    @Test
    void manuallyMigratedDatabaseCanBeAdoptedWithoutResettingQuota() throws Exception {
        createLegacyDatabase();
        // Run existing scripts once, then remove their history to model manual deployment.
        flyway(true).migrate();
        execute("DROP TABLE flyway_schema_history",
                "UPDATE pricing_account SET free_scan_used_count=4");
        assertThat(flyway(true).migrate().migrationsExecuted).isEqualTo(3);
        assertThat(query("SELECT min(free_scan_used_count) FROM pricing_account")).isEqualTo("4");
        validateJpaMappings();
    }

    @Test
    void existingDatabaseRequiresExplicitFirstTimeBaseline() throws Exception {
        createLegacyDatabase();
        assertThatThrownBy(() -> flyway(false).migrate()).isInstanceOf(FlywayException.class);
        assertThat(query("SELECT count(*) FROM pack_order")).isEqualTo("1");
        assertThat(query("SELECT count(*) FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='pack_order' AND column_name='client_id'"))
                .isEqualTo("1");
    }

    @Test
    void ownershipMismatchRollsBackTheWholeMigration() throws Exception {
        createLegacyDatabase();
        execute("CREATE TABLE pricing_account (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id BIGINT NOT NULL UNIQUE REFERENCES client(id), scan_usage_month DATE NOT NULL, free_scan_used_count INTEGER NOT NULL DEFAULT 0)",
                "INSERT INTO pricing_account(client_id,scan_usage_month) VALUES (22,CURRENT_DATE)",
                "ALTER TABLE pack_order ADD COLUMN pricing_account_id BIGINT",
                "UPDATE pack_order SET pricing_account_id=1");
        assertThatThrownBy(() -> flyway(true).migrate()).isInstanceOf(FlywayException.class);
        assertThat(query("SELECT count(*) FROM pricing_account")).isEqualTo("1");
        assertThat(query("SELECT client_id FROM pack_order WHERE id=33")).isEqualTo("11");
        assertThat(query("SELECT count(*) FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='partner_subscription' AND column_name='pricing_account_id'"))
                .isEqualTo("0");
    }

    private Flyway flyway(boolean baseline) {
        return Flyway.configure().dataSource(dataSource).schemas(schema).defaultSchema(schema)
                .locations("classpath:db/migration").baselineVersion("20261104")
                .baselineOnMigrate(baseline).cleanDisabled(true).validateMigrationNaming(true).load();
    }

    private void createLegacyDatabase() throws Exception {
        Flyway.configure().dataSource(dataSource).schemas(schema).defaultSchema(schema)
                .locations("classpath:db/migration").target("20261104").load().migrate();
        execute("DROP TABLE flyway_schema_history",
                "INSERT INTO client(id,email,name,status,plan) VALUES (11,'one@example.com','one','ACTIVE','FREE'),(22,'two@example.com','two','ACTIVE','PARTNER')",
                "INSERT INTO pack_order(id,client_id,purchased_at,expired_at,type,status,total_pages,remaining_pages,price_paid) VALUES (33,11,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP+INTERVAL '1 year','PACK_5','PAID',5,4,49000)",
                "INSERT INTO partner_subscription(id,client_id,purchased_at,expired_at,tier,status,monthly_price) VALUES (44,22,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP+INTERVAL '1 month','PARTNER','ACTIVE',99000),(45,11,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP+INTERVAL '1 month','PARTNER','CANCELLED',99000)");
    }

    private void validateJpaMappings() {
        LocalContainerEntityManagerFactoryBean factory = new LocalContainerEntityManagerFactoryBean();
        factory.setDataSource(dataSource);
        factory.setPackagesToScan("com.malgeum.geo.domain");
        factory.setJpaVendorAdapter(new HibernateJpaVendorAdapter());
        factory.setJpaPropertyMap(Map.of(
                "hibernate.hbm2ddl.auto", "validate",
                "hibernate.default_schema", schema,
                "hibernate.physical_naming_strategy", "org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy"));
        try {
            factory.afterPropertiesSet();
        } finally {
            if (factory.getObject() != null) factory.destroy();
        }
    }

    private void execute(String... statements) throws Exception {
        try (Connection connection = dataSource.getConnection(); Statement sql = connection.createStatement()) {
            connection.setSchema(schema);
            for (String statement : statements) sql.execute(statement);
        }
    }

    private String query(String statement) throws Exception {
        try (Connection connection = dataSource.getConnection(); Statement sql = connection.createStatement()) {
            connection.setSchema(schema);
            try (var result = sql.executeQuery(statement)) {
                assertThat(result.next()).isTrue();
                return result.getString(1);
            }
        }
    }
}
